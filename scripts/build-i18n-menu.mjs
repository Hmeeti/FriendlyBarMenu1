function translit(s) {
  return [...s].map((ch) => (lat[ch] != null ? lat[ch] : ch)).join('');
}

function applyPairs(name, pairs) {
  let out = name;
  for (const [from, to] of pairs) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  return out.replace(/\s+/g, ' ').trim();
}

function translate(name, lang) {
  if (!name) return name;
  if (exact[name]) return exact[name][lang];
  let out = applyPairs(name, lang === 'en' ? pairsEn : pairsKk);
  if (lang === 'en' && /[а-яё]/i.test(out)) {
    out = translit(out);
  }
  // tidy english
  if (lang === 'en') {
    out = out
      .replace(/\bWith\b/g, 'with')
      .replace(/\s+/g, ' ')
      .trim();
    out = out.charAt(0).toUpperCase() + out.slice(1);
  }
  return out || name;
}

